class PredictorUnitStub:
    """Pure deterministic unit-test double; never presented as a registry model."""

    feature_version = "v1"
    feature_signature = feature_signature()
    model_name = "unit-test-only"
    model_version = "1"
    run_id = "unit-test-run"
    threshold = 0.6
    qualified = True
    qualification_policy = {
        "alert_cooldown_seconds": 1800,
        "false_alert_budget_per_machine_day": 2.0,
        "min_recall": 0.70,
        "min_lead_seconds": 300,
        "max_p95_inference_ms": 1000.0,
    }

    def __init__(self, score=0.9):
        self.score = score

    def predict(self, feature):
        return self.score


class UnavailablePredictor(PredictorUnitStub):
    def predict(self, feature):
        raise RuntimeError("unit-test injected prediction failure")


def records_for(events, partitions=1):
    offsets = {partition: 0 for partition in range(partitions)}
    records = []
    for event in events:
        key = "|".join(event[field] for field in ("dataset_id", "site_id", "machine_id")) if isinstance(event, dict) else "invalid"
        partition = int.from_bytes(hashlib.sha256(key.encode()).digest()[:8], "big") % partitions
        records.append({
            "topic": "unit-fixture", "partition": partition, "offset": offsets[partition],
            "value": canonical_json(event) if isinstance(event, dict) else event,
            "published_at": None,
        })
        offsets[partition] += 1
    return records


def rows(store, table):
    assert table in {"features", "predictions", "alerts", "events", "labels"}
    return [json.loads(row["body"]) for row in store.db.execute(f"SELECT body FROM {table}")]


def stable_predictions(predictions):
    return sorted(
        [{key: value for key, value in row.items() if key not in {"predicted_at_epoch", "inference_ms", "arrival_to_prediction_ms"}} for row in predictions],
        key=lambda row: row["feature_id"],
    )


@pytest.mark.parametrize("partitions", [1, 3, 7])
@pytest.mark.parametrize("chunk_size", [1, 17, 10000])
def test_sink_features_match_arrival_replay_across_chunk_and_partition_counts(tmp_path, partitions, chunk_size):
    fixture = generate_dataset(machines=3, sites=2, hours=2, anomalies=True)
    expected_features = causal_feature_rows(fixture["events"])
    source = records_for(fixture["events"], partitions)
    with Store(tmp_path / "sink.sqlite") as store:
        store.activate(PredictorUnitStub())
        for batch_id, offset in enumerate(range(0, len(source), chunk_size)):
            store.process_batch(source[offset:offset + chunk_size], "parity", batch_id, PredictorUnitStub())
        assert sorted(rows(store, "features"), key=lambda row: row["feature_id"]) == sorted(expected_features, key=lambda row: row["feature_id"])
        observed = store.counts()
        expected = fixture["manifest"]["expected_dispositions"]
        assert observed["raw"] == expected["source"]
        assert observed["accepted"] == expected["accepted_sensor"]
        assert observed["label"] == expected["accepted_label"]
        assert observed["control"] == expected["accepted_heartbeat"]
        assert observed["rejected"] == expected["rejected"]
        assert observed["duplicate"] == expected["duplicates"]
        assert observed["predictions"] == observed["features"]
        assert observed["pending_events"] == 0
        assert store.verify()["valid"]


@pytest.mark.parametrize("failpoint", ["before_commit", "after_commit"])
def test_reopen_and_replay_at_commit_boundaries_has_no_partial_or_duplicate_effects(tmp_path, failpoint):
    source = records_for(generate_dataset(machines=2, sites=2, hours=2, anomalies=True)["events"], partitions=3)
    reference_path = tmp_path / "reference.sqlite"
    with Store(reference_path) as baseline:
        baseline.activate(PredictorUnitStub())
        baseline.process_batch(source, "reference", 0, PredictorUnitStub())
        expected_counts = baseline.counts()
        expected_features = sorted(rows(baseline, "features"), key=lambda row: row["feature_id"])
        expected_predictions = stable_predictions(rows(baseline, "predictions"))
    path = tmp_path / "recovered.sqlite"
    with Store(path) as interrupted:
        interrupted.activate(PredictorUnitStub())
        with pytest.raises(InjectedFailure, match=failpoint):
            interrupted.process_batch(source, "recovery", 0, PredictorUnitStub(), failpoint=failpoint)
        if failpoint == "before_commit":
            assert interrupted.counts()["raw"] == 0
            assert interrupted.counts()["features"] == 0
            assert interrupted.counts()["batches"] == 0
        else:
            assert interrupted.counts() == expected_counts
    with Store(path) as recovered:
        result = recovered.process_batch(source, "recovery", 0, PredictorUnitStub())
        assert result.get("batch_replay", False) is (failpoint == "after_commit")
        assert recovered.counts() == expected_counts
        assert sorted(rows(recovered, "features"), key=lambda row: row["feature_id"]) == expected_features
        assert stable_predictions(rows(recovered, "predictions")) == expected_predictions
        assert recovered.verify()["valid"]


def test_same_coordinates_under_new_batch_identity_do_not_duplicate_business_rows(tmp_path):
    source = records_for(generate_dataset(machines=1, sites=1, hours=1)["events"])
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(source, "first", 0, PredictorUnitStub())
        before = store.counts()
        replay = store.process_batch(source, "new-checkpoint", 0, PredictorUnitStub())
        assert replay["new_coordinates"] == 0
        assert replay["replayed_coordinates"] == len(source)
        after = store.counts()
        assert {key: value for key, value in before.items() if key != "batches"} == {key: value for key, value in after.items() if key != "batches"}
        assert after["batches"] == before["batches"] + 1


def test_conflicting_batch_or_kafka_coordinate_fails_without_mutating_state(tmp_path):
    source = records_for(generate_dataset(machines=1, sites=1, hours=1)["events"])
    changed = copy.deepcopy(source)
    changed[0]["value"] = changed[0]["value"].replace('"schema_version":"1"', '"schema_version":"2"')
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(source, "stable", 0, PredictorUnitStub())
        before = store.counts()
        with pytest.raises(ValueError, match="batch identity"):
            store.process_batch(changed, "stable", 0, PredictorUnitStub())
        with pytest.raises(ValueError, match="coordinate content"):
            store.process_batch(changed, "stable", 1, PredictorUnitStub())
        assert store.counts() == before
        assert store.verify()["valid"]


def test_event_id_content_conflict_is_a_quarantined_new_record(tmp_path):
    events = generate_dataset(machines=1, sites=1, hours=1)["events"]
    first_sensor = next(event for event in events if event["kind"] == "sensor")
    conflict = {**first_sensor, "temperature_c": first_sensor["temperature_c"] + 1.0}
    source = records_for([first_sensor, conflict])
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(source, "collision", 0)
        assert store.counts()["raw"] == 2
        assert store.counts()["events"] == 1
        assert store.counts()["rejected"] == 1
        assert rows(store, "events") == [first_sensor]
        assert store.verify()["valid"]


@pytest.mark.parametrize("model_kind", ["missing", "incompatible", "signature", "throws", "nan", "out_of_range"])
def test_model_failure_retains_features_for_later_scoring(tmp_path, model_kind):
    source = records_for(generate_dataset(machines=1, sites=1, hours=2)["events"])
    model = PredictorUnitStub()
    if model_kind == "missing":
        model = None
    elif model_kind == "incompatible":
        model.feature_version = "unimplemented-v2"
    elif model_kind == "signature":
        model.feature_signature = "0" * 64
    elif model_kind == "throws":
        model = UnavailablePredictor()
    elif model_kind == "nan":
        model.score = float("nan")
    else:
        model.score = 1.5
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(source, "pending", 0, model)
        assert store.counts()["features"] > 0
        assert store.counts()["predictions"] == 0
        assert store.counts()["pending_predictions"] == store.counts()["features"]
        store.activate(PredictorUnitStub())
        written = store.score_pending(PredictorUnitStub())
        assert written == store.counts()["features"]
        assert store.counts()["pending_predictions"] == 0
        assert store.score_pending(PredictorUnitStub()) == 0
        assert store.verify()["valid"]


def test_labels_obey_snapshot_cutoff_and_features_are_identical_without_labels(tmp_path):
    fixture = generate_dataset(machines=1, sites=1, hours=3)
    labels = [event for event in fixture["events"] if event["kind"] == "label"]
    cutoff = min(parse_time(label["available_at"]) for label in labels) - 1
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(records_for(fixture["events"]), "labels", 0, PredictorUnitStub())
        assert all(prediction["label"] is None for prediction in store.snapshot(as_of=cutoff)["predictions"])
        matured = store.snapshot(as_of=parse_time(fixture["manifest"]["last_arrival_at"]) + 1)["predictions"]
        assert matured and all(prediction["label"] is not None for prediction in matured)
        for prediction in matured:
            assert prediction["label"]["prediction_event_id"] == prediction["event_id"]
        with Store(tmp_path / "no-labels.sqlite") as no_labels:
            no_labels.process_batch(records_for([event for event in fixture["events"] if event["kind"] != "label"]), "nolabels", 0, PredictorUnitStub())
            assert sorted(rows(store, "features"), key=lambda row: row["feature_id"]) == sorted(rows(no_labels, "features"), key=lambda row: row["feature_id"])


def test_cooldown_is_per_machine_and_actual_feature_availability(tmp_path):
    source = records_for(generate_dataset(machines=2, sites=2, hours=3)["events"], partitions=3)
    with Store(tmp_path / "sink.sqlite") as store:
        store.activate(PredictorUnitStub())
        store.process_batch(source, "cooldown", 0, PredictorUnitStub())
        alerts = rows(store, "alerts")
        assert {alert["machine_id"] for alert in alerts} == {"machine-000", "machine-001"}
        for machine in {alert["machine_id"] for alert in alerts}:
            times = sorted(parse_time(alert["available_at"]) for alert in alerts if alert["machine_id"] == machine)
            assert len(times) > 1
            assert all(current - previous >= 1800 for previous, current in zip(times, times[1:]))


def test_store_output_matches_feature_prediction_alert_schemas(tmp_path):
    import jsonschema

    root = Path(__file__).parents[1] / "schemas"
    source = records_for(generate_dataset(machines=1, sites=1, hours=1)["events"])
    with Store(tmp_path / "sink.sqlite") as store:
        store.activate(PredictorUnitStub())
        store.process_batch(source, "schemas", 0, PredictorUnitStub())
        for name in ("feature", "prediction", "alert"):
            validator = jsonschema.Draft202012Validator(json.loads((root / f"{name}.v1.json").read_text()), format_checker=jsonschema.FormatChecker())
            output = rows(store, f"{name}s")
            assert output
            for row in output:
                validator.validate(row)


