def test_dashboard_store_reader_does_not_mutate_database(tmp_path):
    path = tmp_path / "persisted.sqlite"
    with Store(path) as writer:
        writer.process_batch(records_for(generate_dataset(machines=1, sites=1, hours=1)["events"]), "reader", 0, PredictorUnitStub())
        expected = writer.counts()
    before = hashlib.sha256(path.read_bytes()).hexdigest()
    with Store(path, readonly=True) as reader:
        assert reader.snapshot()["counts"] == expected
        assert reader.verify()["valid"]
        with pytest.raises(sqlite3.OperationalError, match="readonly"):
            reader.set_runtime("forbidden", {})
    assert hashlib.sha256(path.read_bytes()).hexdigest() == before


def test_label_for_another_machine_does_not_attach_as_reality(tmp_path):
    """A syntactically valid label must also match the referenced observation identity."""
    fixture = generate_dataset(machines=1, sites=1, hours=2)
    events = [copy.deepcopy(event) for event in fixture["events"]]
    target = next(event for event in events if event["kind"] == "label" and event["prediction_event_id"].endswith("e0000003"))
    target["machine_id"] = "another-machine"
    with Store(tmp_path / "sink.sqlite") as store:
        store.process_batch(records_for(events), "badlabel", 0, PredictorUnitStub())
        prediction = next(item for item in store.snapshot()["predictions"] if item["event_id"] == target["prediction_event_id"])
        assert prediction["label"] is None
        assert store.counts()["rejected"] == 1


