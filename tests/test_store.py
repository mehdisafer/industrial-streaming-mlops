def test_internal_feature_error_rolls_back_batch_instead_of_misclassifying_source(tmp_path, monkeypatch):
    source = records_for(generate_dataset(machines=1, sites=1, hours=1)["events"])

    def implementation_fault(*args, **kwargs):
        raise ValueError("injected internal feature implementation fault")

    monkeypatch.setattr("industrial_mlops.store.build_features", implementation_fault)
    with Store(tmp_path / "sink.sqlite") as store:
        with pytest.raises(ValueError, match="internal feature"):
            store.process_batch(source, "internal-fault", 0, PredictorUnitStub())
        assert store.counts()["raw"] == 0
        assert store.counts()["events"] == 0

