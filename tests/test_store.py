def test_byte_saturation_rejects_whole_batch_before_any_sink_effect(tmp_path):
    config = PipelineConfig(max_batch_bytes=1024)
    source = records_for(generate_dataset(machines=1, sites=1, hours=1)["events"])
    assert sum(len(record["value"].encode()) for record in source) > config.max_batch_bytes
    with Store(tmp_path / "bounded.sqlite", config) as store:
        with pytest.raises(ValueError, match="byte|bound"):
            store.process_batch(source, "too-large", 0)
        assert store.counts()["raw"] == 0
        assert store.counts()["batches"] == 0


